export function sessionsForTherapist(therapistName: string, date = TODAY) {
  return THERAPY_SESSIONS.filter((s) => s.therapist === therapistName && s.date === date).sort((a, b) =>
    a.time.localeCompare(b.time),
  )
}

export function sessionsForPatient(patientId: string) {
  return THERAPY_SESSIONS.filter((s) => s.patientId === patientId)
}

